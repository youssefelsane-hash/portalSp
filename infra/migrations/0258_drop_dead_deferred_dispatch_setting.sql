-- docs/08 §125 — إعداد `matching.deferred_dispatch_lead_hours` بقى بلا أي قارئ.
--
-- آلية تأجيل بث المطابقة (ADR-0009 بند 1-2) اتوقفت عمليًا من ساعة ADR-0018: كل طلب غير طوارئ
-- بيتأكّد فورًا، وطلب الطوارئ ميقدرش يكون عنده `scheduled_at` أصلاً — فالقيمة المحسوبة كانت
-- `undefined` دايمًا، و`OrderDispatchListener` كان بيتجاهلها تمامًا. الكود (الطابور + الـworker
-- + الدالة النقية + الحقل في الحدث) اتشال بالكامل في نفس الشغل ده، والإعداد بيتشال معاه: إعداد
-- ظاهر في لوحة الإدارة ومالوش أي أثر أسوأ من مفيش إعداد.
DELETE FROM settings WHERE key = 'matching.deferred_dispatch_lead_hours';
