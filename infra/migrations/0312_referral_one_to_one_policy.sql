-- 0312 — نموذج الترشيح ١:١ (docs/08 §135-ح، طلب المالك 2026-09-09)
--
-- طلب المالك بالحرف: «لو رشحت حد من صحابك هتاخد خصم برضه»، وفي البحث الملحق: ترشيح بعد أول
-- طلب بـ١٠٠ جنيه **للطرفين**.
--
-- النموذج القديم كان «كل ١٠ ترشيحات مكتملة = كود واحد للمُرشِّح» — رقم اتحط كقيمة تجريبية
-- (موثّق كده في `modules/referrals/README.md`)، ومعناه عمليًا إن ٩ من كل ١٠ ترشيحات ناجحة
-- **مالهاش أي مقابل ظاهر**، وده بيقتل الحافز اللي الميزة موجودة عشانه.
--
-- **مفيش نظام جديد**: نفس محرك `referrals` بالحرف — بس عتبة المكافأة بقت ١. الجانب التاني
-- (المُرشَّح بياخد خصم على أول طلب) هو `marketing.first_order_*` نفسه (§135-و)، فالطرفين
-- بياخدوا خصم من نفس محرك `promo_codes` بلا مسار تاني.
--
-- القيمة (`referral.reward_value_egp`) بتفضل زي ما هي — قرار مبلغ منفصل، الأدمن يغيّره من
-- الإعدادات وقت ما يقرر.

UPDATE settings
SET value = '1'::jsonb,
    description = 'عدد الترشيحات المكتملة اللي بتدّي كود مكافأة للمُرشِّح. القيمة ١ = مكافأة عن كل ترشيح ناجح (نموذج ١:١، docs/08 §135-ح).',
    updated_at = NOW()
WHERE key = 'referral.required_referrals_per_reward';
