-- baytak — 0201: مدخلات العميل على الطلب كـsnapshot ظاهر للأدمن والفني (docs/08 §71)
--
-- طلب المالك: «البيانات اللي العميل بيكتبها عن الطلب مفروض تكون ظاهرة على الأقل للأدمن وجزء منها
-- ظاهر للصنايعي… لما الأدمن يدخل على الطلب يعرف والله الكاستمر كان مختار الحاجات دي ودي… حاجة
-- بسيطة، سطر كلام».
--
-- الوضع قبل ده: `field_values` اللي العميل بيملاها في الفورم الديناميكي كانت بتتخزن في
-- `service_pricing_evaluations.field_values` — **بس لخدمات pricing_model='formula'**. أي خدمة
-- تانية عندها حقول ديناميكية، إجابات العميل كانت بتتبخّر بعد حساب السعر: مفيش أي مكان في المنصة
-- يعرض للأدمن ولا للفني العميل اختار إيه.
--
-- ليه عمود على `orders` مش JOIN وقت العرض؟ **snapshot** بنفس فلسفة باقي المشروع
-- (order_earning_shares.share_weight، بيانات الإنتاجية المحسوبة): الأدمن ممكن يعدّل اسم الحقل أو
-- يمسحه بعد الحجز، والطلب لازم يفضل يقول اللي العميل شافه واختاره **وقتها** بالظبط. والتسميات
-- محلولة عربي جوّه الـsnapshot، فالعرض في 3 واجهات بصفر استعلامات إضافية.
--
-- الشكل: [{"key":"area","label":"المساحة","value":"25","unit":"م²"}] — مصفوفة عشان ترتيب العرض
-- (display_order) يتحفظ زي ما العميل شافه.

ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_inputs jsonb;

COMMENT ON COLUMN orders.customer_inputs IS
  'snapshot لإجابات العميل على الحقول الديناميكية وقت الحجز (تسميات عربية محلولة) — للعرض بس، التسعير بيستخدم service_pricing_evaluations.';
