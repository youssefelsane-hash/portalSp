-- baytak — 0272: جدول إيجارات الدورات المجدولة (بديل القفل الاستشاري على مستوى الجلسة)

-- **المشكلة اللي الجدول ده موجود عشانها — عطل حقيقي اتعاد إنتاجه، مش تحسين نظري.**
--
-- تدقيق A-2 خلّى كل دورة مجدولة تاخد `pg_try_advisory_lock` عشان نسخة واحدة بس تشتغل. القفل
-- الاستشاري ده **مربوط بالجلسة**: عشان يفضل ماسك طول الدورة، لازم الاتصال يفضل محجوز طول
-- الدورة. يعني كل دورة شغّالة = اتصال من pool التطبيق متشال من الخدمة.
--
-- وقت الإقلاع بيتسجّل ١٤ مؤقّت بـ٦٠ ثانية + واحد بـ١٥ ثانية، فكلهم بيولعوا في نفس التِك عند
-- الدقيقة الأولى. الـpool الافتراضي ١٠ اتصالات، منهم ٢ محجوزين دايمًا لـ`LISTEN`، فالمتاح ٨:
--
--   ٨ دورات بتاخد الـ٨ اتصالات كلها للأقفال،
--   وكل واحدة فيهم بتعمل استعلامها الحقيقي فتطلب اتصال تاسع…
--   مش هييجي أبدًا، لأن اللي ماسكينه مستنيينه.
--
-- ومفيش مهلة اقتناء افتراضية في node-postgres ⇒ الانتظار **أبدي**. النتيجة: `/health` وطلب
-- الـOTP وكل حركة المستخدمين بتتعلّق للأبد، والعملية مابترجعش لوحدها حتى لو قتلت الجلسات.
--
-- **الحل**: إيجار (lease) بمهلة في جدول، بدل قفل مربوط بالجلسة. الاقتناء والتجديد والتحرير
-- **استعلام قصير واحد** كل مرة — الاتصال بيرجع للـpool فورًا، ومفيش أي اتصال محجوز طول الدورة.
-- الحصرية عبر النسخ محفوظة بنفس القوة: `ON CONFLICT ... WHERE expires_at <= now()` ذرّي في
-- عبارة واحدة، فنسخة واحدة بس هي اللي بتاخد الصف.
--
-- **ليه مش Redis**: Redis في المشروع ده معرَّف صراحةً كـ«مش مصدر حقيقة أبدًا» ومسموح يقع من غير
-- ما يكسر عملية (`redis-cache.service.ts`). لو الحصرية اتعلّقت بيه، وقوعه يبقى إما إيقاف كل
-- الدورات أو تشغيلها مرتين (تحصيل مكرر). القاعدة أصلاً شرط لازم لأي دورة — فهي المكان الصح.
--
-- **مفيش `deleted_at`**: ده جدول تنسيق لحظي مش سجل دومين. صف «متشال منطقيًا» معناه قفل ميت
-- بيمنع الدورة للأبد — عكس الغرض بالظبط. الصف بيفضل موجود بعد التحرير عمدًا (`expires_at` في
-- الماضي) عشان يبقى فيه أثر تشغيلي: مين آخر نسخة شغّلت الدورة دي وإمتى.

CREATE TABLE IF NOT EXISTS sweep_leases (
  id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  lock_name         text        NOT NULL UNIQUE,
  -- توكن الحائز: بيمنع نسخة قديمة (اتأخرت وإيجارها خلص واتاخد منها) إنها تجدّد أو تحرّر إيجار
  -- بقى ملك نسخة تانية. من غيره، تحرير متأخر بيفتح الدورة لنسخة تالتة في نفس اللحظة.
  holder_token      uuid        NOT NULL,
  holder_instance   text        NOT NULL,
  acquired_at       timestamptz NOT NULL DEFAULT now(),
  renewed_at        timestamptz NOT NULL DEFAULT now(),
  expires_at        timestamptz NOT NULL,
  -- إحصاءات تشغيلية خفيفة: بتخلّي «الدورة دي واقفة من ساعة» سؤال باستعلام واحد.
  run_count         bigint      NOT NULL DEFAULT 0,
  last_released_at  timestamptz,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_at        timestamptz NOT NULL DEFAULT now()
);

-- الاستعلام الوحيد اللي بيتعمل بكثرة هو الاقتناء بـ`lock_name`، والـUNIQUE فوق بيغطيه.
-- الفهرس ده للتشخيص بس: «مين ماسك إيجار حي دلوقتي» (dev-doctor + لوحة العمليات).
-- **من غير `WHERE expires_at > now()`**: Postgres بيرفض دوال غير IMMUTABLE في شرط الفهرس
-- (`functions in index predicate must be marked IMMUTABLE`)، والجدول ده صغير أصلاً (صف لكل
-- دورة) فالفهرس الكامل أرخص من أي لفّ حوالين القيد ده.
CREATE INDEX IF NOT EXISTS idx_sweep_leases_expires_at ON sweep_leases (expires_at DESC);

COMMENT ON TABLE sweep_leases IS
  'إيجارات الدورات المجدولة — حصرية عبر النسخ من غير حجز اتصال من pool التطبيق (بديل pg_try_advisory_lock على مستوى الجلسة).';
