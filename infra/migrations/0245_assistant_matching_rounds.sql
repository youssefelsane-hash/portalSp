-- ADR-0061 §4 — جولات بث المساعدين.
--
-- قبل كده كان فيه **جولة واحدة**: أول دفعة مرشّحين تاخد عرض، ولو محدش رد في المهلة الطلب بيتصعّد
-- للعمليات فورًا — حتى لو فيه عشرات المساعدين المؤهلين لسه ماتسألوش أصلاً. ده مش نقص ميزة، ده
-- تصعيد كاذب: العمليات بتتنده لتغطية شغل الغطاء التلقائي بتاعه موجود ومتاح.
--
-- العمود ده بيخلي «الجولة» حقيقة مسجّلة مش استنتاج من التوقيت: بيحدد كل عرض في أنهي دفعة اتبعت،
-- وبيدّي job الانتهاء لكل جولة معرّف مستقل (BullMQ بيتجاهل add لمعرّف موجود، فمعرّف واحد لكل
-- الجولات كان معناه إن مؤقّت الجولة التانية مايشتغلش خالص والطلب يعلّق للأبد بدل ما يتصعّد).

ALTER TABLE order_assistant_offers
  ADD COLUMN IF NOT EXISTS matching_round smallint NOT NULL DEFAULT 1;

COMMENT ON COLUMN order_assistant_offers.matching_round IS
  'رقم جولة البث اللي العرض ده اتبعت فيها (1 = أول دفعة). التصعيد للعمليات بيحصل بس لما جولة ترجع صفر مرشّح جديد.';

CREATE INDEX IF NOT EXISTS idx_assistant_offers_order_round
  ON order_assistant_offers (order_id, matching_round DESC);
