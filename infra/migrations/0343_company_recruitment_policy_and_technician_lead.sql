-- سياسة تجنيد الشركة + اشتراط أن يكون القائد فنيًا (ADR-0086، docs/08 §141 بنود ٣ و٨).
--
-- العمودين الاتنين `NOT NULL DEFAULT false`، يعني **صفر تغيير سلوك** على أي بيانات قايمة:
-- كل الشركات الحالية بتفضل زي ما هي (تجنيد مفتوح زي دلوقتي بالظبط — راجع التعليق تحت)، وكل
-- الخدمات الحالية بتفضل تحت قاعدة ADR-0055 بالحرف (المساعد المؤهّل بياخد الطلب كقائد).

-- ① سياسة تجنيد الشركة (بند ٨):
--
-- > «عند كل بروفايل شركة، من عندي أنا كأدمن أحدد هل الشركة دي يحق لها لما يجيلها شغلانة
-- >  وتحتاج تدعو فنيين أو مساعدين، تدعوهم من الفنيين اللي موجودين في المنصة كمان، ولا لأ —
-- >  هم community مقفولة على نفسها ويختاروا من نفسهم بس.»
--
-- **الافتراضي `false` (مقفولة)** مقصود: السلوك الحالي إن قائد أي طلب يقدر يجنّد أي حد على
-- المنصة، وده أوسع من اللي المالك يقصده بكلمة «شركة». فتح الباب بقى قرار إداري صريح لكل
-- شركة على حدة، مش وضع تلقائي بيتوسّع بالسكوت.
--
-- ومربوط ببند ٩: القيد بيسري بس على الطلب اللي `orders.assigned_company_id` بتاعته = الشركة
-- دي. نفس الفني على طلب **خاص بيه** بيجنّد من المنصة كلها زي أي مستقل، لأن الطلب ده مش طلب
-- الشركة أصلاً (`MatchingService.resolveAssignedCompanyId()`).
ALTER TABLE technician_companies
  ADD COLUMN IF NOT EXISTS allows_external_recruitment boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN technician_companies.allows_external_recruitment IS
  'هل الشركة تقدر تجنّد من مجمع المنصة كله لطلباتها (assigned_company_id = الشركة دي)؟ false = مقفولة على طاقمها. ADR-0086.';

-- ② اشتراط أن يكون قائد الطلب فنيًا كاملاً (بند ٣):
--
-- > «الطلب مسموح له فقط إن هو يروح لفنيين فقط، بيروح لأحسن فني.»
--
-- **خاصية للخدمة مش قاعدة عامة**، و`false` افتراضيًا — عشان ADR-0055 (قرار مالك صريح: «طالما
-- أنا ما منعتش عنهم الشغل، يبقى زيهم زي الفنيين بالضبط») يفضل ساري بالحرف على كل الخدمات
-- الحالية. الأدمن بيشغّل الاشتراط على الخدمات اللي فعلاً محتاجة فني كامل بس.
--
-- وبيتطبّق في **نفس** `technicianAvailabilityCondition` المشتركة، فبيسري على التوزيع التلقائي
-- والترشيح الداخلي جوّه الشركة وقايمة تجنيد الطاقم بنفس الحرف — «نفس قواعدنا» بمعناها الحرفي.
ALTER TABLE services
  ADD COLUMN IF NOT EXISTS requires_technician_lead boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN services.requires_technician_lead IS
  'لما true: قائد الطلب لازم يكون technician_kind = technician (المساعد ماياخدش الطلب كقائد). false = قاعدة ADR-0055 العادية. ADR-0086.';
