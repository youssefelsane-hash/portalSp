-- تحققت الأول: مفيش أي timestamp مكافئ في المنظومة. `responded_at` بتتكتب عند القبول/الرفض بس،
-- و`order_status_history` مالهاش علاقة بحالة العرض، والانتقال sent→viewed بيحصل في مكان واحد
