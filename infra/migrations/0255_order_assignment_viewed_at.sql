-- الدلالة المعتمدة: **أول** مشاهدة (`viewed_at` بتتكتب مرة واحدة وماتتغيّرش بعدها) — عشان
-- «اتبعت 14:01:02 / اتشاف 14:01:11 / اترفض 14:01:27» تبقى قراءة صادقة لزمن الاستجابة الحقيقي.
