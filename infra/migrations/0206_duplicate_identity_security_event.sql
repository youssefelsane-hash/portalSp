-- baytak — 0206: نوع حدث أمني جديد لمحاولة استخدام هوية محجوزة (ADR-0045 §3)
--
-- لما حد يحاول يسجّل برقم قومي مربوط بحساب فني تاني، الرد **مش** بيقول لمين الرقم (وإلا أي حد
-- بيجرّب أرقام يقدر يستخرج قاعدة بيانات هوية). بس ده بالظبط اللي المالك عايز يمسكه: «لو فني
-- حصل منه مشكلة، ما يروحش جاي رايح مسجل برقم تليفون تاني». فالمحاولة نفسها بتتسجّل كحدث أمني
-- بالتفاصيل الكاملة (الحساب الأصلي + حالته + المحاوِل)، والأدمن بيشوفها في مركز الأمان.
--
-- `ALTER TYPE ... ADD VALUE` مسموح جوّه transaction من PostgreSQL 12 — بشرط ما تستخدمش القيمة
-- الجديدة في نفس الـtransaction، وده مش بيحصل هنا (إضافة بس).
ALTER TYPE security_event_type ADD VALUE IF NOT EXISTS 'duplicate_identity_attempt';
