-- عتبات إنذارات المراقبة (ج-٧) كصفوف إعدادات حقيقية.
--
-- **الفجوة اللي بيقفلها**: `OpsMetricsService` بيقرا العتبات بـ`getNumber(key, fallback)`، فمن
-- غير الصفوف دي القيم بتشتغل من الـfallback في الكود — يعني الأرقام صح، لكن **الأدمن مايقدرش
-- يشوفها ولا يعدّلها**: شاشة الإعدادات بتقرا من الجدول، و`PATCH /admin/settings/:key` بيرمي 404
-- لمفتاح مش موجود (اتقاس حيًا في تدقيق ج-٧). النتيجة إن «العتبات قابلة للضبط بلا deploy» كان
-- ادعاء غير صحيح عمليًا.
--
-- ضبط العتبة وقت الحادثة (مثلاً تهدئة إنذار بيرن كتير الساعة ٣ الفجر، أو تشديده قبل موسم) هو
-- بالظبط نوع التحكم اللي بند ج-١٨ بيطلبه: **من غير نشر كود**.
--
-- القيم هنا **مطابقة للـfallback في الكود بالحرف** — البذر ده مش تغيير سياسة، هو بس بيخلي
-- السياسة القائمة مرئية وقابلة للتعديل. أي تغيير حقيقي في الحساسية قرار تشغيلي للمالك.
