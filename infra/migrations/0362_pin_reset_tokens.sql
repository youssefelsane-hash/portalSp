-- **أكواد استرجاع رمز الدخول** (ADR-0109 §6-ب، إصلاح فجوة حقيقية).
--
-- ## الفجوة اللي الجدول ده بيقفلها
--
-- `POST /admin/users/:id/pin/reset` كان بيمسح رمز المستخدم **ويلغي كل جلساته**. والمستخدم اللي
-- محتاج الاسترجاع ده هو **بالتحديد** اللي عامل logout ونسي رمزه — يعني بعد الاسترجاع:
--
--   * مايقدرش يدخل من شاشة الدخول (مفيش رمز).
--   * مايقدرش يستخدم `POST /auth/pin` (محتاج توكن صالح، ومفيش جلسة).
--   * ومفيش SMS خلاص بعد التبديل.
--
-- **طريق مسدود تام.** الاسترجاع كان بيقفل الحساب بدل ما يفتحه.
--
-- ## ليه كود لمرة واحدة، مش «الأدمن يحط رمز مؤقت»
--
-- الخيار التاني مرفوض في ADR-0109 §6-ب لسبب سليم: لو الأدمن اختار الرمز، يبقى فيه بني آدم تاني
-- **يعرف سر دخول العميل** ولازم يتقال في مكالمة تليفون — تسريب بالتصميم، والأسوأ إن أغلب الناس
-- مابتغيّرش الرمز المؤقت بعد كده.
--
-- الكود هنا **مش** رمز دخول: هو تصريح لمرة واحدة يخوّل صاحبه **يختار** رمز. مايفتحش جلسة،
-- ومايرجّعش توكن، ومابيدّي أي وصول للحساب لوحده. أقرب حاجة ليه في المشروع هي أكواد استرجاع
-- الـMFA (`admin_mfa_recovery_codes`) — نفس النمط بالظبط.
--
-- ## الحماية
--
-- | | القاعدة |
-- |---|---|
-- | التخزين | `bcrypt` — الكود الخام عمره ما يتخزّن، زي `otp_codes.code_hash` |
-- | العمر | ١٥ دقيقة. مدة مكالمة دعم، مش أكتر |
-- | الاستهلاك | مرة واحدة (`used_at`)، صف حقيقي في Postgres مش Redis — الاستهلاك لازم يكون fail-closed |
-- | المحاولات | ٥ محاولات على الكود نفسه، وبعدها يبطل نهائيًا |
-- | التعدد | إصدار كود جديد **بيبطّل** كل الأكواد القديمة للمستخدم — مايبقاش فيه تصريحين حيين |
-- | الأثر | `issued_by_user_id` — مين من الدعم أصدره. مفيش إثبات تقني لهوية العميل في مكالمة، فالسجل هو الأثر الوحيد |

CREATE TABLE IF NOT EXISTS pin_reset_tokens (
  id uuid PRIMARY KEY DEFAULT uuid_generate_v7(),
  user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- هاش الكود الخام. الأدمن بيشوف الكود مرة واحدة وقت الإصدار وبس.
  code_hash varchar(255) NOT NULL,
  expires_at timestamptz NOT NULL,
  used_at timestamptz,
  -- محاولات غلط على الكود ده. بتوصل السقف ⇒ الكود ميت، ولازم الدعم يصدر واحد جديد.
  failed_attempts smallint NOT NULL DEFAULT 0,
  -- **مين أصدره** — الأثر الوحيد القابل للمراجعة على إجراء مابيثبتش هوية صاحب الحساب تقنيًا.
  issued_by_user_id uuid NOT NULL REFERENCES users (id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  deleted_at timestamptz
);

-- الاستعلام الوحيد على الجدول: «الأكواد الحية للمستخدم ده». الفهرس الجزئي بيخليه فهرس صغير
-- مهما كبر الجدول، لأن الأكواد المستهلكة/المنتهية مش بتتقرا تاني.
CREATE INDEX IF NOT EXISTS idx_pin_reset_tokens_live
  ON pin_reset_tokens (user_id)
  WHERE used_at IS NULL AND deleted_at IS NULL;

COMMENT ON TABLE pin_reset_tokens IS
  'أكواد استرجاع رمز الدخول (ADR-0109 §6-ب) — تصريح لمرة واحدة يخوّل صاحبه يختار رمز جديد. مش رمز دخول ومابيفتحش جلسة.';
