-- **محتوى صفحة الخدمة للظهور في البحث** (ADR-0113، طلب مالك 2026-09-25).
--
-- عمود واحد على نفس نمط `safety_guidance_ar` بالحرف (migration 0337): نص عربي يكتبه الأدمن من
-- شاشة الخدمة، وبيتعرض في صفحة عامة مفهرَسة على `/services/{slug}`.
--
-- ### وجود المحتوى **هو** مفتاح النشر — مفيش `is_seo_published`
--
-- ده طلب المالك بالنص («أي حاجة بنضيفها في الجزء ده بتبتدي تظهر»)، وبيقفل مشكلة حقيقية مجانًا:
-- الكتالوج فيه خدمات اختبار متسرّبة (`tsc-service-…`, `signup-drain-…`). علم نشر منفصل كان ممكن
-- يتفتح عليها بالغلط؛ أما محتوى تسويقي مكتوب بإيد الأدمن فعمره ما هيتكتب لخدمة اختبار.
--
-- ### مفيش `seo_title_ar`
--
-- العنوان بيتركّب من `name_ar` + اسم المنطقة. حقل عنوان منفصل معناه عنوان يقدر يخالف اسم الخدمة
-- نفسها — تعارض بيظهر للزائر وللزاحف مع أول تعديل على واحد منهم بلا التاني.

ALTER TABLE services
  ADD COLUMN IF NOT EXISTS seo_content_ar text;

-- الصفحات العامة والـsitemap بيسألوا «الخدمات المنشورة» على كل زيارة. الفهرس الجزئي ده بيخدم
-- الاستعلام ده بالتحديد وحجمه بعدد الخدمات المنشورة بس، مش بعدد الخدمات كلها.
CREATE INDEX IF NOT EXISTS idx_services_seo_published
  ON services (slug)
  WHERE seo_content_ar IS NOT NULL AND deleted_at IS NULL AND is_active;

COMMENT ON COLUMN services.seo_content_ar IS
  'محتوى صفحة الخدمة العامة للظهور في البحث (ADR-0113). NULL أو فاضي = مفيش صفحة منشورة.';
