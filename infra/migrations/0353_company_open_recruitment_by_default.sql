-- الشركة مش مقفولة على نفسها افتراضيًا (docs/08 §163، ADR-0086 تعديل ١، طلب مالك 2026-09-17).
--
-- ADR-0086 خلّى `allows_external_recruitment` افتراضيه `false` عمدًا، والمبرر وقتها إن فتح
-- الباب يبقى «قرار إداري صريح لكل شركة». الواقع بعد كده: **مفيش واجهة أدمن للمفتاح ده خالص**،
-- فالقرار الصريح مكانش ممكن يتاخد أصلاً — الـ١٨ شركة كلها `false` والميزة مقفولة عمليًا.
--
-- المالك طلب صراحةً: «مش عايزين تكون الشركة مغلقة على نفسها… يكون الطلب قادر يدعو أي حد سواء
-- من جوا الشركة أو من برا الشركة». فالافتراضي بيتعكس، والقفل بيفضل متاح كـ**استثناء صريح**
-- من واجهة الأدمن (نفس الـendpoint ونفس الـaudit بتوع ADR-0086 — صفر مسار جديد).
--
-- **التحديث بيمسّ الشركات القايمة عن قصد**: كلها على القيمة الافتراضية القديمة، ومحدش اختار
-- القفل بإرادته (مكانش فيه زرار). لو شركة محتاجة تتقفل، الأدمن بيقفلها من الواجهة الجديدة
-- والقرار ده بيتسجّل في `audit_logs` باسم الموظف — وده الفرق: قفل مقصود ومراجَع بدل قفل
-- افتراضي صامت.

ALTER TABLE technician_companies
  ALTER COLUMN allows_external_recruitment SET DEFAULT true;

UPDATE technician_companies
   SET allows_external_recruitment = true, updated_at = now()
 WHERE allows_external_recruitment = false;

COMMENT ON COLUMN technician_companies.allows_external_recruitment IS
  'هل الشركة تقدر تجنّد من مجمع المنصة كله لطلباتها (assigned_company_id = الشركة دي)؟ الافتراضي true (مفتوحة) من docs/08 §163؛ false = مقفولة على طاقمها بقرار أدمن صريح مسجّل في audit_logs. ADR-0086 + تعديل ١.';
