-- فهرس على `risk_signal_types.updated_by_user_id` — مفتاح أجنبي كان بلا فهرس داعم
-- (تدقيق ماراثوني 2026-09-14، docs/08 §148، المرحلة ٩).
--
-- ## ليه ده مهم
--
-- Postgres بيعمل فهرس تلقائي على الطرف **المُشار إليه** (المفتاح الأساسي) بس، مش على الطرف
-- المُشير. فأي `DELETE` أو `UPDATE` على `users` لازم يتأكد إن مفيش صف في `risk_signal_types`
-- بيشاور على المستخدم ده — ومن غير فهرس ده `seq scan` على الجدول كله في كل مرة. وحذف مستخدم
-- مسار حقيقي عندنا (`/auth/account` — حذف الحساب، §99-ب).
--
-- ## ليه الجدول ده بالذات فات
--
-- الجدول اتضاف مع مركز المخاطر (ADR-0085). `check-db-hygiene.js` هو الحارس اللي المفروض
-- يمسك الفئة دي، بس هو نفسه كان بيرفض يشتغل من غير `DATABASE_URL` صريح في البيئة بدل ما
-- يقراه من `apps/api/.env` زي باقي الأدوات — فكان بيتخطّى في كل تشغيلة ومحدش واخد باله.
-- الأداة اتظبطت في نفس الدفعة دي، وأول تشغيلة ناجحة ليها طلعت الصف ده.
--
-- `WHERE ... IS NOT NULL` لأن العمود بيقبل NULL (الصفوف المزروعة مالهاش مُعدِّل)، فالفهرس
-- الجزئي بيغطي الاستعلام المطلوب بحجم أصغر.

CREATE INDEX IF NOT EXISTS idx_risk_signal_types_updated_by_user_id
  ON risk_signal_types (updated_by_user_id)
  WHERE updated_by_user_id IS NOT NULL;
