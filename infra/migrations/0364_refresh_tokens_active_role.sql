-- **الدور النشط بيتخزّن مع الجلسة** (ADR-0110 §5).
--
-- `refresh()` لازم يطلّع توكن بنفس الدور النشط بالظبط. من غير العمود ده، مستخدم عنده الدورين
-- (عميل + صنايعي) يدوّر جلسة تطبيق العميل ويرجع بدور الصنايعي حسب `users.user_type` — **توسيع
-- صلاحية بالتدوير**، وهو بالظبط اللي ADR-0110 بيقول إنه ممنوع.
--
-- `NULL` = جلسة اتعملت قبل المايجريشن دي (أو جلسة موظف على لوحة التحكم). `refresh()` بيرجع
-- ساعتها لـ`users.user_type` — نفس السلوك القديم بالحرف، فمفيش جلسة قايمة بتتكسر.
ALTER TABLE refresh_tokens
  ADD COLUMN IF NOT EXISTS active_role varchar(20);

COMMENT ON COLUMN refresh_tokens.active_role IS
  'الدور اللي الجلسة دي اتصدرت بيه (ADR-0110). التدوير بيحافظ عليه ويعيد التحقق من المنحة. NULL = جلسة قديمة أو موظف.';
