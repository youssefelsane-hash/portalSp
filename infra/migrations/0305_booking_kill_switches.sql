-- مفاتيح طوارئ لإيقاف الحجز الجديد بلا نشر كود (ج-١٧ التدهور الانتقائي + ج-١٨ تحكّم الأدمن).
--
-- **الفجوة اللي بيقفلها**: كان فيه مفتاح إيقاف لكل **وسيلة دفع** (`payments.*_enabled`) لكن
-- **مفيش أي مفتاح لإيقاف الحجز نفسه**. يعني وقت حادثة حقيقية — خلل تسعير بيحسب غلط، بوابة دفع
-- بتفشل، مفيش فنيين بيستلموا — الخيار الوحيد قدام المالك كان **نشر كود** (دقايق في أحسن
-- الأحوال، تحت ضغط وبقرارات متسرّعة) أو يسيب الضرر يكبر كل دقيقة.
--
-- **مفتاحين مش واحد، عمدًا**: الطوارئ (حجز نفس اليوم) أعلى مخاطرة — بتتجاهل الجدول، بتوصل
-- لفنيين مشغولين، وسعرها أعلى. لو المشكلة في الطوارئ وحدها، إيقاف الحجز كله عقوبة جماعية على
-- أعمال سليمة تمامًا.
--
-- **الإيقاف انتقائي مش شامل** — دي القاعدة الحاكمة لج-١٧ والسبب إن الحارس بيتنادى من مسار
-- إنشاء الطلب **وبس**: الفني اللي واقف عند باب العميل لازم يقدر يقفل الشغل، والعميل اللي خلص
-- شغله لازم يقدر يدفع، والإلغاء/الشكوى/الشات لازم تفضل شغّالة. الإيقاف الشامل بيحوّل مشكلة في
-- الحجز لأزمة في كل مكان. التفاصيل الكاملة في `apps/api/src/modules/orders/booking-availability.guard.ts`.
--
-- القيمتين `true` = السلوك الحالي بالحرف. البذر ده مش تغيير سياسة — هو بس بيخلّي القدرة على
-- الإيقاف **موجودة قبل ما نحتاجها**، لأن وقت الحادثة مش وقت كتابة migration.
INSERT INTO settings (key, value, value_type, group_name, description, is_public)
SELECT v.key, v.value::jsonb, 'boolean', 'orders', v.description, false
FROM (VALUES
  ('orders.new_bookings_enabled', 'true',
   'مفتاح طوارئ: لما يتقفل، أي طلب جديد بيترفض برسالة عربية مؤقتة. الطلبات القائمة وتنفيذها ودفعها وإلغاؤها بتفضل شغّالة عادي.'),
  ('orders.emergency_bookings_enabled', 'true',
   'مفتاح طوارئ أضيق: بيوقف حجوزات نفس اليوم (الطوارئ) وحدها والحجز العادي يفضل شغّال. مفيد لما المشكلة في الطوارئ بس فإيقاف الحجز كله يبقى عقوبة جماعية.')
) AS v(key, value, description)
WHERE NOT EXISTS (SELECT 1 FROM settings s WHERE s.key = v.key);
