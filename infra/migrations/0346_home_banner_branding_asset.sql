-- 0346 — خانة بانر الشاشة الرئيسية (بلاغ مالك 2026-09-15، docs/08 §150 بند ٣، ADR-0095)
--
-- طلب المالك: «تضيفلي مكان أحط فيه الصورة، تكون ظاهرة بالهيئة المستطيلة الجميلة دي… وتترفع من
-- يا إما البراندينج يا إما الواجهة الرئيسية عند الأدمين».
--
-- الاختيار وقع على **البراندينج** لأنه الموديول الوحيد اللي عنده مسار **رفع ملف** حقيقي
-- (تحقق أبعاد + حجم + تخزين + رابط بيتولّد وقت القراءة، ADR-0014). صفحة «الواجهة الرئيسية»
-- بتاخد **روابط** بس، فكانت هتسيب المالك يدوّر على استضافة بره المنصّة عشان يحط صورة.
--
-- مفيش قيمة افتراضية حقيقية للبانر عمدًا: `GET /branding` بيرجّع عنصر نائب بـ`is_default=true`،
-- والواجهات بتخفي الخانة كلها في الحالة دي. يعني إضافة النوع ده لوحدها **صفر تغيير مرئي** لحد
-- ما الأدمن يرفع صورة فعلاً.

ALTER TYPE branding_asset_type ADD VALUE IF NOT EXISTS 'home_banner';
