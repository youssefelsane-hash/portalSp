-- baytak — 0200: نسبة حصة المساعد من حصة الفني داخل الطاقم (docs/08 §66، ADR-0043)
--
-- طلب المالك: «المفروض فيه فنيين وفيه مساعدين… المفروض ده ما بياخدش زي ده، بيكون فيه فرق…
-- مستحسن تكون حاجة مرنة بحيث الـadmin يعرف يعدلها».
--
-- الوضع قبل ده: `splitCrewEarnings` (ADR-0040) بتوزّع بوزن **المستوى** بس
-- (`technician_level_config.crew_share_weight`)، و`participant_role` كان محمول في البيانات لكن
-- **مش داخل الحسبة خالص**. يعني مساعد مستواه `new` كان بياخد بالظبط زي فني مستواه `new`.
--
-- القيمة الافتراضية 0.65 مأخوذة من مثال المالك الحرفي: «لو الفني بياخد 700، المساعد ياخد 450»
-- (450 ÷ 700 = 0.643 ≈ 0.65).
--
-- الحدود (0.10 – 1.00) مقصودة: فوق 1.00 معناه المساعد بياخد أكتر من الفني وده انعكاس للمعنى
-- كله، وتحت 0.10 معناه أجر رمزي مش أجر.

INSERT INTO settings (key, value, value_type, group_name, description, is_public) VALUES
  ('crew.assistant_share_ratio', '0.65', 'number', 'payments',
   'نسبة حصة المساعد من حصة الفني في نفس المستوى داخل الطاقم (0.65 = المساعد بياخد 65% من اللي الفني بياخده). بتتضرب في وزن المستوى، مش بديل عنه.',
   false)
ON CONFLICT (key) DO NOTHING;
