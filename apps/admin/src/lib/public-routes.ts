/**
 * **المسارات اللي بتتفتح قبل تسجيل الدخول** — مصدر واحد (ADR-0111).
 *
 * كان `/login` مكتوب بنص حرفي في مكانين (`proxy.ts` و`app-shell.tsx`)، فإضافة `/activate`
 * كانت بتتنسى في واحد منهم. وده حصل فعلاً: الصفحة اتعملت وكانت بترجّع تحويل لـ`/login` — يعني
 * الموظف الجديد **لسه** مش قادر يوصل لمكان التفعيل، وهي نفس الفجوة اللي الشغل ده بيقفلها.
 *
 * `/activate` **لازم** تكون هنا: الموظف الجديد مالوش جلسة بحكم التعريف — ده سبب وجود الصفحة.
 * الأمان في كود التنشيط نفسه (١٠ أرقام، ١٥ دقيقة، لمرة واحدة، bcrypt، عدّاد محاولات على السيرفر)،
 * مش في حارس الجلسة.
 */
export const PRE_AUTH_ROUTES = new Set(['/login', '/activate']);

export function isPreAuthRoute(pathname: string): boolean {
  return PRE_AUTH_ROUTES.has(pathname);
}
