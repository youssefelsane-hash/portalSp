import 'package:flutter/material.dart';

/// بيحطّ [destination] فوق الشاشة الرئيسية مباشرةً **وبيشيل كل اللي بينهم**.
///
/// ## البَقّة اللي وراه (بلاغ المالك 2026-09-11)
///
/// «علشان أرجع لصفحة البداية بدوس على السهم كذا مرة، والسهم بيرجّعني تاني على صفحة الفنيين
/// وعلى صفحة الطلب».
///
/// شاشة إنشاء الطلب كانت بتعمل `pushReplacement` — وده بيستبدل **شاشة الإنشاء بس**. كل اللي
/// تحتها (الخدمة ← الموعد ← اختيار الفني) بيفضل في المكدّس، فالعميل بعد ما يحجز بيرجع بالسهم
/// لشاشات حجز **اتعمل خلاص**.
///
/// **وده مش إزعاج بصري بس**: من شاشة الفنيين القديمة دي، اختيار فني تاني بيفتح
/// `CreateOrderScreen` **جديدة بمفتاح idempotency جديد** — يعني **طلب تاني حقيقي** على نفس
/// الشغلانة. حماية الـidempotency بتغطّي إعادة الإرسال من **نفس** الشاشة، مش رحلة جديدة كاملة.
///
/// `(route) => route.isFirst` بتسيب الشاشة الرئيسية في القاع: السهم من تفاصيل الطلب بيرجّع
/// للرئيسية مباشرة، والتطبيق مايخرجش.
///
/// **مفصولة في دالة مسمّاة عشان تتقاس**: `create_order_screen.dart` محتاجة شبكة وحالة كاملة
/// عشان توصل لسطر التنقّل، فاختبار المكدّس من جوّاها مش عملي. الدالة دي مدخلها `BuildContext`
/// وودجت، فاختبار حقيقي يقدر يبني مكدّس ويتأكد إنه اتنضّف فعلاً.
Future<T?> replaceBookingStack<T>(BuildContext context, WidgetBuilder destination) {
  return Navigator.of(context).pushAndRemoveUntil<T>(
    MaterialPageRoute<T>(builder: destination),
    (route) => route.isFirst,
  );
}
