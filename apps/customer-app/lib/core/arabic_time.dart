/// **صياغة الوقت داخل نص عربي** (بلاغ مالك 2026-09-16، docs/08 §152).
///
/// > «الكلام اللي مكتوب لما حد بيترشح، الكلام عربي على إنجليزي على أرقام، فكلام بيبين إن هو
/// >  مش مضبوط أو شكله مش نظيف.»
///
/// ### البَقّة اللي الملف ده اتكتب عشانها
///
/// `TimeOfDay.format(context)` بترجّع **`11:55 AM`** — فيها حروف لاتينية (`AM`)، وهي في
/// الـUnicode Bidi «قوية LTR». لما تتحط جوّه جملة عربية، خوارزمية الاتجاه بتعيد ترتيب المقطع
/// كله ومعاه علامات الترقيم المجاورة، فالجملة بتتقطّع وتعيد ترتيب نفسها على الشاشة:
///
///   المكتوب : «السعر ده محجوز لك مع الأسطى ده لحد 11:55 AM. لو غيّرت أي تفصيلة هنرشّح من جديد.»
///   المعروض : «لو غيّرت أي AM. السعر ده محجوز لك مع الأسطى ده لحد 11:55 .تفصيلة هنرشّح من جديد.»
///
/// ### الحل بشقّين، والاتنين لازمين
///
/// 1. **مفيش حروف لاتينية**: `ص`/`م` بدل `AM`/`PM`. ده لوحده بيشيل المصدر الأقوى للانقلاب.
/// 2. **عزل الاتجاه** (`FSI`…`PDI`): الأرقام في Bidi «ضعيفة»، فساعة زي `11:55` جنب نقطة أو
///    فاصلة لسه بتقدر تسحب الترقيم معاها. محارف العزل بتخلّي المقطع وحدة واحدة مقفولة على
///    نفسها، فمستحيل يتفاعل مع اللي حواليه — ودي القاعدة اللي بتمنع رجوع البَقّة من أي نص تاني.
///
/// أي وقت بيتعرض جوّه جملة عربية لازم يعدّي من هنا.
library;

import 'package:flutter/material.dart';

/// First Strong Isolate — بداية مقطع معزول اتجاهيًا.
const String _fsi = '\u2068';

/// Pop Directional Isolate — نهاية المقطع المعزول.
const String _pdi = '\u2069';

/// بيلفّ أي مقطع بأرقام/لاتيني في عزل اتجاهي، فمايأثرش على ترتيب الجملة العربية حواليه.
String isolateBidi(String value) => '$_fsi$value$_pdi';

/// `11:55 ص` — بلا أي حرف لاتيني، ومعزولة اتجاهيًا فجاهزة للحطّ جوّه جملة عربية.
///
/// ٢٤ ساعة بتتحوّل لـ١٢ ساعة بلاحقة عربية: منتصف الليل `12:05 ص` والظهر `12:30 م`.
String formatArabicTime(TimeOfDay time) {
  final suffix = time.hour < 12 ? 'ص' : 'م';
  final hour12 = time.hour % 12 == 0 ? 12 : time.hour % 12;
  final minute = time.minute.toString().padLeft(2, '0');
  return isolateBidi('$hour12:$minute $suffix');
}

/// نفس الدالة فوق لكن من `DateTime` — بتتحوّل للتوقيت المحلي الأول.
String formatArabicTimeOfDay(DateTime dateTime) =>
    formatArabicTime(TimeOfDay.fromDateTime(dateTime.toLocal()));
