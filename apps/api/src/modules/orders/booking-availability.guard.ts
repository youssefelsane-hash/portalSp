import { HttpStatus, Injectable } from '@nestjs/common';
import { ApiException, ErrorCode } from '../../common/exceptions/api.exception';
import { SettingsService } from '../settings/settings.service';

/**
 * **مفاتيح الطوارئ لإيقاف الحجز الجديد — بلا نشر كود** (ج-١٧ + ج-١٨).
 *
 * ## المشكلة اللي بيحلها
 *
 * كان فيه مفاتيح إيقاف لكل **وسيلة دفع** (`payments.*_enabled`) لكن **مفيش أي طريقة لإيقاف
 * الحجز نفسه**. يعني وقت حادثة حقيقية — بوابة الدفع بتفشل، الفنيين مش بيستلموا، خلل تسعير
 * بيحسب غلط — الخيار الوحيد أمام المالك كان **نشر كود** (دقايق في أحسن الأحوال، وتحت ضغط
 * وبقرارات متسرّعة) أو يسيب الضرر يكبر.
 *
 * ## القاعدة الحاكمة: التدهور **انتقائي** مش شامل
 *
 * ده جوهر ج-١٧ — «مين مسموح يوقف الحجز ومين لأ». إيقاف الحجز الجديد **ممنوع منعًا باتًا** إنه
 * يلمس الشغل الجاري:
 *
 * | العملية | لما الحجز يتوقف |
 * |---|---|
 * | عميل بيعمل طلب **جديد** | **يتوقف** برسالة عربية واضحة |
 * | فني رايح لعميل / بيبدأ / بيقفل شغل | **يكمّل عادي** |
 * | عميل بيدفع لشغل **خلص** | **يكمّل عادي** |
 * | إلغاء / شكوى / شات / دعم | **يكمّل عادي** |
 * | طلب دوري متولّد من خطة قائمة | **يكمّل عادي** — العميل اتعاقد عليه قبل الحادثة |
 *
 * السبب مش تقني: عميل الفني واقف عند بابه ومش قادر يقفل الشغل، أو عميل خلص شغله ومش قادر
 * يدفع — دول **ضرر أكبر** من الحادثة اللي بنحاول نحتويها. الإيقاف الشامل بيحوّل مشكلة في
 * الحجز لأزمة في كل مكان.
 *
 * ## مفتاحين مش واحد
 *
 * - `orders.new_bookings_enabled` — الإيقاف الكامل للحجز الجديد.
 * - `orders.emergency_bookings_enabled` — الطوارئ وحدها.
 *
 * الفصل مقصود: الطوارئ أعلى مخاطرة (بتتجاهل الجدول، بتوصل لفنيين مشغولين، سعرها أعلى). لو
 * المشكلة في الطوارئ بس، إيقاف الحجز كله عقوبة جماعية على أعمال سليمة.
 *
 * ## إزاي بيتغيّر وقت الحادثة
 *
 * `PATCH /admin/settings/orders.new_bookings_enabled` بقيمة `false` (يحتاج `settings.manage`
 * + توكن step-up). بيسري **فورًا** بلا إعادة تشغيل — `SettingsService` بيبطّل الكاش المحلي
 * وRedis مع الكتابة. اتقاس حيًا في ج-٧ (`ر-٣/أ`) وفي ج-١٧.
 *
 * **الكتابة المباشرة بـSQL مش كافية** — بتعدّي على الكاش فالقيمة القديمة بتفضل شغّالة.
 */
@Injectable()
export class BookingAvailabilityGuard {
  constructor(private readonly settings: SettingsService) {}

  /**
   * المفتاح العام — بيتنادى **بدري** في `create()` قبل أي تسعير أو مطابقة أو كتابة.
   *
   * الترتيب مقصود: الفحص ده نداء إعدادات واحد مكاشّف، فرفض الطلب قبل عشرات الاستعلامات
   * بيخلّي المفتاح **يخفّف الحمل فعلاً** وقت الحادثة بدل ما يبقى مجرد رسالة في الآخر. لو
   * السبب في إيقاف الحجز أصلاً هو ضغط على القاعدة، فحص متأخر كان هيزوّد الضغط لا يقلّله.
   *
   * @param isRecurringGenerated طلب متولّد من خطة قائمة — بيعدّي عمدًا (العميل اتعاقد قبل الحادثة).
   */
  async assertNewBookingsAllowed(isRecurringGenerated = false): Promise<void> {
    if (isRecurringGenerated) return;
    if (await this.settings.getBoolean('orders.new_bookings_enabled', true)) return;
    // الرسالة بتقول **إيه اللي حصل وإيه اللي المفروض يعمله** — «حصل خطأ» بتخلّي العميل
    // يعيد المحاولة عشرين مرة ويتصل بالدعم. الحالة دي مؤقتة بطبيعتها فالرسالة بتقول كده،
    // وبتطمّنه صراحةً إن طلباته القائمة ماتأثرتش (وده صح فعلاً، مش تطمين فاضي).
    throw new ApiException(
      ErrorCode.SYS_002,
      'الحجز متوقّف مؤقتًا لأعمال صيانة — طلباتك الحالية شغّالة عادي، وجرّب تاني بعد شوية',
      HttpStatus.SERVICE_UNAVAILABLE,
    );
  }

  /**
   * المفتاح الأضيق — بيتنادى **بعد** اشتقاق الاستعجال في `create()` (ADR-0048: الوضع مشتق من
   * التاريخ في الباك-إند، مش مختار من العميل)، لأن قبل كده مفيش إجابة على «ده طوارئ ولا لأ».
   */
  async assertEmergencyBookingsAllowed(isRecurringGenerated = false): Promise<void> {
    if (isRecurringGenerated) return;
    if (await this.settings.getBoolean('orders.emergency_bookings_enabled', true)) return;
    // **بديل حقيقي مش رفض جاف**: الطوارئ متوقفة بس الحجز العادي شغّال، والرسالة بتقول كده
    // صراحةً عشان العميل يعرف إن قدامه طريق مش إنه مقفول عليه.
    throw new ApiException(
      ErrorCode.SYS_002,
      'خدمة الطوارئ متوقّفة مؤقتًا — تقدر تحجز بموعد عادي دلوقتي، أو جرّب الطوارئ تاني بعد شوية',
      HttpStatus.SERVICE_UNAVAILABLE,
    );
  }
}
